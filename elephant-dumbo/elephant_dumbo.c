static uint8_t reverse_bits(uint8_t value)
{
  value = (uint8_t)((value & 0x55u) << 1 | (value >> 1 & 0x55u));
  value = (uint8_t)((value & 0x33u) << 2 | (value >> 2 & 0x33u));
  return (uint8_t)(value << 4 | value >> 4);
}

static uint8_t permutation_index(uint8_t index)
{
  return index == 159 ? index : (uint8_t)((index * 40u) % 159u);
}

static void spongent_first_round(uint8_t state[STATE_BYTES])
{
  uint8_t permuted[STATE_BYTES] = {0};
  uint8_t counter = DUMBO_COUNTER;

  state[0] ^= counter;
  state[STATE_BYTES - 1] ^= reverse_bits(counter);

  for (uint8_t i = 0; i < STATE_BYTES; ++i)
  {
    state[i] = sbox[state[i]];
  }

  for (uint8_t byte = 0; byte < STATE_BYTES; ++byte)
  {
    for (uint8_t bit = 0; bit < 8; ++bit)
    {
      uint8_t target = permutation_index((uint8_t)(8u * byte + bit));
      permuted[target / 8u] |= (uint8_t)(((state[byte] >> bit) & 1u) << (target % 8u));
    }
  }

  for (uint8_t i = 0; i < STATE_BYTES; ++i)
  {
    state[i] = permuted[i];
  }
}

int main(void)
{
  uint8_t state[STATE_BYTES];

  for (int trace = 0; trace < NOTRACES; ++trace)
  {
    for (uint8_t i = 0; i < STATE_BYTES; ++i)
    {
      randbyte(&state[i]);
    }

    /* The first four bytes are the fixed mask under attack. */
    for (uint8_t i = 0; i < MASK_BYTES; ++i)
    {
      state[i] ^= MASK[i];
    }

    starttrigger();
    spongent_first_round(state);
    endtrigger();

    for (uint8_t i = 0; i < TARGET_BYTES; ++i)
    {
      printbyte(&state[i]);
    }
  }

  endprogram();
  return 0;
}
