/*
 * Trace-oriented implementation of the first SPONGENT-160 round for Dumbo.
 * The S-box and bit permutation match the full SPONGENT implementation;
 * only one round is executed so its intermediate state can be measured.
 *
 * A full implementation of elephant 160 is available at
 * `https://csrc.nist.gov/CSRC/media/Projects/lightweight-cryptography/documents/finalist-round/updated-submissions/elephant.zip`
 */

#include <stdint.h>

#include "../thirdparty/elmo/Examples/elmoasmfunctionsdef.h"

#define NOTRACES 200
#define STATE_BYTES 20
#define TARGET_BYTES 4
#define DUMBO_COUNTER 0x75

#define MASK_BYTES 5

static const uint8_t MASK[MASK_BYTES] = {
    0x13,
    0x37,
    0xa5,
    0xc9,
};

